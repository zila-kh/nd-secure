fn ensure_fallback_icon() {
    let manifest_dir = PathBuf::from(
        env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is not set"),
    );
    let icon_dir = manifest_dir.join("icons");
    let icon_path = icon_dir.join("icon.png");

    if icon_path.exists() {
        return;
    }

    fs::create_dir_all(&icon_dir).expect("failed to create Tauri icon directory");
    fs::write(&icon_path, FALLBACK_ICON_PNG).expect("failed to write fallback Tauri icon");
}

fn main() {
    ensure_fallback_icon();
    tauri_build::build()
}
